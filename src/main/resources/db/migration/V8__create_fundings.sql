CREATE TABLE fundings
(
    id                              BIGINT        NOT NULL AUTO_INCREMENT,
    owner_id                        BIGINT        NOT NULL,
    recipient_id                    BIGINT        NULL,
    funding_type                    VARCHAR(20)   NOT NULL,
    status                          VARCHAR(30)   NOT NULL,
    title                           VARCHAR(20)   NOT NULL,
    target_amount                   BIGINT        NOT NULL,
    deadline                        DATETIME(6)   NOT NULL,
    reveal_at                       DATETIME(6)   NULL,
    story                           VARCHAR(300)  NULL,
    promise                         VARCHAR(300)  NULL,
    source_wish_id                  BIGINT        NULL,
    product_name                    VARCHAR(20)   NOT NULL,
    product_image_url               VARCHAR(2048) NOT NULL,
    product_price                   BIGINT        NOT NULL,
    product_url                     VARCHAR(2048) NOT NULL,
    source_payout_account_id        BIGINT        NULL,
    payout_bank                     VARCHAR(30)   NOT NULL,
    payout_encrypted_account_number VARCHAR(255)  NOT NULL,
    payout_account_holder           VARCHAR(100)  NULL,
    extension_count                 INT           NOT NULL DEFAULT 0,
    extended_at                     DATETIME(6)   NULL,
    result_opened_at                DATETIME(6)   NULL,
    gift_prepared_at                DATETIME(6)   NULL,
    completed_at                    DATETIME(6)   NULL,
    created_at                      DATETIME(6)   NOT NULL,
    updated_at                      DATETIME(6)   NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_fundings_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_fundings_recipient FOREIGN KEY (recipient_id) REFERENCES users (id),
    CONSTRAINT fk_fundings_source_wish FOREIGN KEY (source_wish_id) REFERENCES wishes (id) ON DELETE SET NULL,
    CONSTRAINT fk_fundings_source_payout_account FOREIGN KEY (source_payout_account_id) REFERENCES payout_accounts (id) ON DELETE SET NULL,
    CONSTRAINT chk_fundings_target_amount CHECK (target_amount > 0 AND target_amount <= 10000000),
    CONSTRAINT chk_fundings_product_price CHECK (product_price > 0),
    CONSTRAINT chk_fundings_extension_count CHECK (extension_count BETWEEN 0 AND 1),
    CONSTRAINT chk_fundings_type_fields CHECK (
        (funding_type = 'BIRTHDAY' AND recipient_id IS NULL AND reveal_at IS NULL)
        OR (funding_type = 'SURPRISE' AND recipient_id IS NOT NULL AND reveal_at IS NOT NULL)
    ),
    INDEX idx_fundings_owner_status_deadline (owner_id, status, deadline),
    INDEX idx_fundings_recipient_type_reveal (recipient_id, funding_type, reveal_at)
);
